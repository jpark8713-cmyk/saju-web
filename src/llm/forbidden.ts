// 금지 표현: 질병·의료 판단, 투자 권유·재물 손실 단정, 사망·재앙 단정, 불안을 키우는 단정 (SPEC 1장·Phase 2)
// 정규식 기반이다. 막지 않아야 할 일반 표현("사고 없이", "경험에 투자해 보세요", "절대로 망설이지")은 패턴에서 뺐다.
// 놓친 표현·오탐은 tests/llm/forbidden.test.ts에 문장으로 추가해 고정한다.
import type { ForbiddenRule } from '../config/topics';

/** 낱말 앞 경계 (예: "매출 신장"의 신장, "시간"의 간은 신체 부위가 아니다) */
const FRONT = '(?<![가-힣])';
const BODY_PARTS = '(?:몸|체력|심장|간|콩팥|폐|위|위장|대장|허리|관절|혈관|눈|피부|뼈|갑상선|면역력)';
/** "~에 투자"가 사람·경험·자기계발 같은 비금융 대상이면 막지 않는다 */
const NON_FINANCIAL_TARGET = '(?:시간|노력|에너지|마음|정성|자신|자기 ?계발|배움|공부|관계|인간관계|사람|인연|경험|건강한 습관|취미|휴식)';

export const COMMON_FORBIDDEN: readonly ForbiddenRule[] = Object.freeze([
  {
    pattern:
      '(질병|질환|병에 걸|병이 날|병이 생|암에 걸|당뇨|고혈압|우울증|치료를 받|약을 (드|복용)|수술(?!하듯)|병원(에 가|을 찾|에서 검사)|' +
      '진단(을 받|이 나|됩|받)|건강(이|이 크게)? ?(나빠|악화|안 좋아|해치)|건강(에|을) (유의|조심|주의)|다칠 (수|위험)|' +
      `${FRONT}${BODY_PARTS}(이|가)? ?(약(하|해|한|할|합|해지|해져)|나빠|나쁜|안 좋|탈이)|아플 수|아프게 될)`,
    reason: '질병·의료 판단',
  },
  {
    pattern:
      '(코인|가상화폐|비트코인|ETF|펀드|채권|청약|주식(을|에|으로)? ?(사|투자|넣)|주식 투자|(매수|매도)(하세요|해 보세요|하면 좋|를 권)|' +
      '부동산 ?(투자|매입|구입|을 사)|땅을 사|집을 사|건물을 사|빚을 (내|져)|대출을 받|돈을 (넣|맡기|잃)|파산|손실을 (볼|입)|' +
      `(?<!${NON_FINANCIAL_TARGET}[^.]{0,10})투자(해 보세요|하세요|하십시오|하면 (좋|큰|수익|돈)|를 (권|추천|늘리))|` +
      '수익(을|이) (보장|확실))',
    reason: '투자 권유·재물 손실 단정',
  },
  {
    pattern:
      '(사망|죽음|목숨(?! ?걸)|세상을 떠|요절|단명|재앙|재난(?! ?(대비|예방))|파멸|불행이 닥|화재(?! ?(예방|대비))|' +
      '(교통)?사고(가 날|가 생길|를 당할|를 겪|가 일어날|가 있을)|큰 사고(?! ?(없|를 피))|죽(을 수|는다|게 됩))',
    reason: '사망·재앙 단정',
  },
  {
    pattern:
      '((반드시|틀림없이|무조건|절대(로)?) ?(실패|망하|망치|망합|헤어지|헤어집|불행|아프|잃)|' +
      '이혼(할|하게|수|운| 위험| 가능성)|헤어질 (수|가능성|운))',
    reason: '불안을 키우는 단정',
  },
  { pattern: '(적중|풀이의? 정확도|정확한 풀이|100 ?% ?(맞|적중|정확))', reason: '입증할 수 없는 정확성 표현' },
]);

export function findForbidden(text: string, rules: readonly ForbiddenRule[]): ForbiddenRule[] {
  return rules.filter((r) => new RegExp(r.pattern, 'u').test(text));
}
