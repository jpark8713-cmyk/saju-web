/** 이름 옆 괄호 설명을 뺀 이름(아이디에 쓴다) */
const baseName = (name: string) => name.replace(/\s*\(.*\)$/, '');

export const DISTRICTS: readonly District[] = Object.freeze(
  PROVINCES.flatMap((p) =>
    (RAW[p.id] ?? []).map(([name, longitude]) => Object.freeze({ id: `${p.id}:${baseName(name)}`, provinceId: p.id, name, longitude })),
  ),
);

export function findProvince(id: string): Province | undefined {
  return PROVINCES.find((p) => p.id === id);
}

export function districtsOf(provinceId: string): readonly District[] {
  return DISTRICTS.filter((d) => d.provinceId === provinceId);
}

/** 시도 아이디(시군구 모름) 또는 "시도:시군구" 아이디로 찾는다 */
export function findRegion(id: string): Region | undefined {
  const district = DISTRICTS.find((d) => d.id === id);
  if (district) return { id, name: `${findProvince(district.provinceId)!.name} ${district.name}`, longitude: district.longitude };
  const province = findProvince(id);
  return province ? { id, name: `${province.name} (시군구 모름)`, longitude: province.longitude } : undefined;
}

/** 지역 아이디가 속한 시도 아이디 */
export function provinceIdOf(regionId: string): string {
  return regionId.split(':')[0] ?? '';
}
