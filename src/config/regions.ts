// TODO(owner): 값은 공식 자료(국토지리정보원·행정표준코드)와 한 번 대조한다(D-038).

export interface Province {
  id: string;
  name: string;
  /** 시군구를 모를 때 쓰는 대략적인 중심 경도 */
  longitude: number;
}

export interface District {
  id: string;
  provinceId: string;
  name: string;
  longitude: number;
}

